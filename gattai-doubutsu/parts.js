  /* その ぶいの なまえ（あしの ない ヘビ・しっぽの ない カエル なども ここで） */
  function partName(sp, slot) {
    const p = sp[slot];
    if (slot === "legs" && sp.id === "snake") return "ヘビ（あし なし）";
    if (slot === "legs" && sp.id === "dolphin") return "イルカの ひれ";
    if (slot === "tail" && p.kind === "none") return sp.name + "（しっぽ なし）";
    const word = slot === "tail" ? ({ wing: "つばさ", flipper: "つばさ", fluke: "おびれ" }[p.kind] || "しっぽ") : SLOT_NAME[slot];
    return sp.name + "の " + word;
  }

  /* がったい どうぶつ の え。combo = { head, body, legs, tail }（SPECIES の ばんごう） */
  function drawCreature(combo, opt) {
    opt = opt || {};
    const H = SPECIES[combo.head], B = SPECIES[combo.body], Lg = SPECIES[combo.legs], T = SPECIES[combo.tail];
    const ground = Lg.legs.ground !== false;
    const dy = ground ? 0 : 36;
    const tFront = !!T.tail.front;
    const tailG = `<g class="tailpart ${T.tail.kind}">${T.tail.svg()}</g>`;
    const inner =
      (tFront ? "" : tailG) +
      `<g class="legs mv-${Lg.legs.move}">${Lg.legs.svg()}</g>` +
      `<g class="bodypart">${B.body.svg()}</g>` +
      (tFront ? tailG : "") +
      `<g class="headpart">${H.head.svg()}</g>`;
    const shadow = `<ellipse class="shadow" cx="100" cy="151" rx="56" ry="5" fill="#000" opacity="0.12"/>`;
    return `<svg class="creature${opt.cls ? " " + opt.cls : ""}" viewBox="0 ${opt.top == null ? 0 : opt.top} 200 ${opt.h || 160}" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="${opt.label || ""}">` +
      shadow + `<g class="whole" transform="translate(0 ${dy})"><g class="bob" stroke="#3b2f2f" stroke-width="1.8" stroke-linejoin="round">${inner}</g></g></svg>`;
  }

  /* 1つの ぶいだけ の え（スロット よう）。viewBox は ぶい ごとに きめうち */
  const PART_VIEW = { head: "118 22 76 80", body: "48 30 104 92", legs: "60 96 86 58", tail: "0 0 130 154" };
  function drawPart(spIndex, slot) {
    const sp = SPECIES[spIndex], p = sp[slot];
    const g = p.svg();
    if (!g) return `<svg class="part" viewBox="0 0 100 60" xmlns="http://www.w3.org/2000/svg"><text x="50" y="38" text-anchor="middle" font-size="20" fill="#adb5bd">なし</text></svg>`;
    return `<svg class="part" viewBox="${PART_VIEW[slot]}" xmlns="http://www.w3.org/2000/svg"><g stroke="#3b2f2f" stroke-width="1.8" stroke-linejoin="round">${g}</g></svg>`;
  }

