/* 絵柄が決まっていない駅は、駅名から きまった絵柄を選ぶ(いつも同じになる) */
const FALLBACK_MOTIFS = [
  '🚃', '🚋', '🚉', '🛤️', '🚦', '🎫', '⛲', '🌳', '🌸', '🍀',
  '⭐', '🌙', '☀️', '🌈', '🐟', '🐦', '🦋', '🌻', '🍁', '⛰️',
];

function hashString(str) {
  let h = 0;
  for (let i = 0; i < str.length; i += 1) {
    h = (h * 31 + str.charCodeAt(i)) % 100000;
  }
  return h;
}

function motifFor(name) {
  if (STATION_MOTIFS[name]) return STATION_MOTIFS[name];
  return FALLBACK_MOTIFS[hashString(name) % FALLBACK_MOTIFS.length];
}

/* RAW_LINES を、あつかいやすい形に組み立てなおす */
const LINES = RAW_LINES.map((line) => ({
  id: line.id,
  name: line.name,
  yomi: line.yomi,
  company: line.company,
  color: line.color,
  ink: line.ink,
  symbol: line.symbol,
  note: line.note,
  stations: line.stations.map(([name, yomi], index) => ({
    name,
    yomi,
    motif: motifFor(name),
    index,
    lineId: line.id,
  })),
}));

const LINE_BY_ID = {};
LINES.forEach((line) => {
  LINE_BY_ID[line.id] = line;
});

/* 会社ごとのまとまり(路線えらび画面の並び順) */
const COMPANIES = [];
LINES.forEach((line) => {
  let group = COMPANIES.find((c) => c.name === line.company);
  if (!group) {
    group = { name: line.company, lines: [] };
    COMPANIES.push(group);
  }
  group.lines.push(line);
});

/* 全駅(重複なし)。よみの長さごとに分けておき、4択のダミー作りに使う */
const ALL_STATIONS = [];
const SEEN_STATION = {};
LINES.forEach((line) => {
  line.stations.forEach((st) => {
    if (SEEN_STATION[st.name]) return;
    SEEN_STATION[st.name] = true;
    ALL_STATIONS.push(st);
  });
});

const YOMI_BY_LENGTH = {};
ALL_STATIONS.forEach((st) => {
  const len = st.yomi.length;
  if (!YOMI_BY_LENGTH[len]) YOMI_BY_LENGTH[len] = [];
  YOMI_BY_LENGTH[len].push(st.yomi);
});

const TOTAL_STATION_COUNT = ALL_STATIONS.length;

/*
 * 路線図が見られる路線。
 * 路線図の中身は 駅データから じどうで作るので、収録している路線は ぜんぶ 見られる。
 */
const MAP_LINE_IDS = LINES.map((line) => line.id);

/*
 * のりかえ表
 *   駅名 -> [{ lineId, index }]
 * 同じ駅名が いくつの路線に出てくるかを 駅データから じどうで あつめる。
 * (手で書かないので、路線を足しても かならず つじつまが あう)
 */
const TRANSFER_INDEX = {};
LINES.forEach((line) => {
  line.stations.forEach((st) => {
    if (SEPARATE_STATIONS[`${line.id}|${st.name}`]) return;
    if (!TRANSFER_INDEX[st.name]) TRANSFER_INDEX[st.name] = [];
    TRANSFER_INDEX[st.name].push({ lineId: line.id, index: st.index });
  });
});

// 名前は同じでも べつの場所にある駅か
function isSeparateStation(stationName, lineId) {
  return !!SEPARATE_STATIONS[`${lineId}|${stationName}`];
}

// その駅から のりかえられる 路線(いま乗っている路線は のぞく)
function transfersFor(stationName, currentLineId) {
  if (isSeparateStation(stationName, currentLineId)) return [];
  return (TRANSFER_INDEX[stationName] || [])
    .filter((t) => t.lineId !== currentLineId)
    .map((t) => ({ line: LINE_BY_ID[t.lineId], index: t.index }));
}

// アプリに入っていない路線への のりかえ
function otherTransfersFor(stationName, currentLineId) {
  if (isSeparateStation(stationName, currentLineId)) return [];
  return OTHER_TRANSFERS[stationName] || [];
}
