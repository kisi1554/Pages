/* ============================ ことばを さがす ============================ */

/*
 * さがす用の辞書。ながい ことばから しらべる。
 * どうし(「侮る」など)は かたちが かわる(侮れない・侮って)ので、
 * さいごの 1もじを のぞいた「ごかん」でも さがせるように しておく。
 */
const VERB_TAIL = ['る', 'う', 'く', 'す', 'つ', 'ぶ', 'む', 'ぐ', 'える', 'ける'];

function stemOf(entry) {
  const y = entry.y;
  if (!VERB_TAIL.some((t) => y.slice(-t.length) === t)) return '';
  const stem = entry.w.slice(0, -1);
  if (!stem) return '';
  /* ひらがなだけの ごかんは、みじかいと ほかの ことばと まちがえる */
  const kanaOnly = !/[\u4e00-\u9fff]/.test(stem);
  if (kanaOnly && stem.length < 3) return '';
  return stem;
}

const WORD_LOOKUP = [];
WORDS.forEach((entry) => {
  WORD_LOOKUP.push({ word: entry.w, entry });
  if (entry.y !== entry.w) WORD_LOOKUP.push({ word: entry.y, entry, kana: true });
  const stem = stemOf(entry);
  if (stem && stem !== entry.w) WORD_LOOKUP.push({ word: stem, entry, kana: !/[\u4e00-\u9fff]/.test(stem) });
});
WORD_LOOKUP.sort((a, b) => b.word.length - a.word.length);

const WORD_BY_KEY = {};
WORDS.forEach((entry) => {
  WORD_BY_KEY[entry.w] = entry;
  WORD_BY_KEY[entry.y] = entry;
});

/*
 * ことばの中から、しっている ことばを さがす。
 * よみで さがす ときは、みじかい ことばの まちがいを ふせぐため
 * 3もじ いじょう の ものだけに する。
 */
function findWordEntry(text) {
  const raw = String(text || '');
  const norm = normalize(raw);
  let hit = null;
  WORD_LOOKUP.some((item) => {
    if (item.kana) {
      if (item.word.length < 3) return false;
      if (normalize(raw).indexOf(normalize(item.word)) < 0) return false;
    } else if (raw.indexOf(item.word) < 0 && norm.indexOf(normalize(item.word)) < 0) {
      return false;
    }
    hit = item.entry;
    return true;
  });
  return hit;
}

/* レベルで しぼった ことばの ならび */
function wordsAtLevel(maxLevel) {
  const list = WORDS.filter((entry) => entry.lv <= maxLevel);
  return list.length > 0 ? list : WORDS;
}
