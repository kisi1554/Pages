const Quiz = (function () {
  let $, rb, onDone, i = 0, score = 0, answered = false;
  function render() {
    const q = QUIZ[i];
    $("#qNum").textContent = (i + 1) + " / " + QUIZ.length;
    $("#qText").innerHTML = rb(q.q);
    $("#qExp").innerHTML = ""; $("#qExp").hidden = true;
    $("#qNext").hidden = true;
    $("#qChoices").innerHTML = q.a.map(function (a, k) { return '<button type="button" class="choice" data-k="' + k + '">' + rb(a) + "</button>"; }).join("");
    $("#qChoices").querySelectorAll(".choice").forEach(function (b) { b.onclick = function () { pick(+b.dataset.k); }; });
    answered = false;
    Say.speak(q.q + "。" + q.a.map(function (a, k) { return (k + 1) + "、" + a; }).join("。"));
  }
  function pick(k) {
    if (answered) return;
    answered = true;
    const q = QUIZ[i], ok = k === q.ans;
    if (ok) { score++; Snd.ok(); } else Snd.ng();
    $("#qChoices").querySelectorAll(".choice").forEach(function (b, n) {
      b.classList.add(n === q.ans ? "right" : n === k ? "wrong" : "dim"); b.disabled = true;
    });
    $("#qExp").innerHTML = (ok ? "⭕ せいかい！ " : "❌ ざんねん。 ") + rb(q.exp);
    $("#qExp").hidden = false;
    $("#qNext").hidden = false;
    $("#qNext").textContent = i + 1 < QUIZ.length ? "つぎの もんだい ▶" : "けっかを みる 🎉";
    Say.speak((ok ? "せいかい。" : "ざんねん。") + q.exp);
  }
  function next() {
    Snd.tap();
    if (i + 1 < QUIZ.length) { i++; render(); return; }
    $("#qBox").hidden = true; $("#qResult").hidden = false;
    const msg = score === QUIZ.length ? "ぜんもん せいかい！ {水|みず}の はかせだ！" : score >= 7 ? "すごい！ よく しってるね。" : "ためしに たびや じっけんを してから、もう いちど ちょうせん！";
    $("#qScore").innerHTML = "🎯 " + score + " / " + QUIZ.length + " もん せいかい<br>" + rb(msg);
    Say.speak(score + "もん せいかい。" + msg);
    if (score >= 7) Snd.fanfare();
    if (onDone) onDone(score);
  }
  function start() { i = 0; score = 0; $("#qBox").hidden = false; $("#qResult").hidden = true; render(); }
  function init(o) { $ = o.$; rb = o.rb; onDone = o.onDone; $("#qNext").onclick = next; $("#qAgain").onclick = start; }
  return { init: init, start: start };
})();
