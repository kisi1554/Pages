/*
 * data-plus-*.js から よばれる。もじれつは「なまえ=せつめい」、めいさんは「絵文字 なまえ=せつめい」。
 *
 *  spot / food / geo / mame … もとの データに たしこむ
 *  city    : おもな まち          matsuri : まつり・ぎょうじ
 *  rail    : てつどう・えき        hito    : ゆかりの ひと
 *  hogen   : ほうげん              shizen  : やま・かわ・みずうみ・しま
 *  rekishi : れきし                sym     : [けんの はな, けんの き, けんの とり]
 *  chimei  : よみかたが むずかしい ちめい
 */
const PAIR_KEYS = ['city', 'matsuri', 'rail', 'hito', 'hogen', 'shizen', 'chimei'];

function splitPair(s) {
  const i = s.indexOf('=');
  return i < 0 ? [s, ''] : [s.slice(0, i), s.slice(i + 1)];
}

function addKnowledge(code, o) {
  const p = PREFS[code];
  // おなじ なまえが もう ある ときは たさない
  const key = (s) => s.replace(/\[([^|\]]+)\|([^\]]+)\]/g, '$2').replace(/\s/g, '')
    .replace(/[\u30a1-\u30f6]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60));
  const hasName = (list, n) => list.some((x) => key(x) === key(n));
  (o.spot || []).forEach((s) => { const x = splitPair(s); if (!hasName(p.spot.map((y) => y[0]), x[0])) p.spot.push(x); });
  (o.food || []).forEach((s) => {
    const sp = s.indexOf(' ');
    const [name, note] = splitPair(s.slice(sp + 1));
    if (!hasName(p.food.map((y) => y[1]), name)) p.food.push([s.slice(0, sp), name, note]);
  });
  p.geo.push(...(o.geo || []));
  p.mame.push(...(o.mame || []));
  PAIR_KEYS.forEach((k) => { p[k] = (p[k] || []).concat((o[k] || []).map(splitPair)); });
  p.rekishi = (p.rekishi || []).concat(o.rekishi || []);
  if (o.sym) p.sym = o.sym;
}

